def validate_jwt_refresh(jwt_token):
    """
    1. Browser sends cookie in the form of Cookie: "vault_access=eyJB..."
    2. we extract and parse the string into the format of a dict of token_name: jwt token
    3. when we call jwt.decode(token, ACCESS_SECRET), it
        splits the token into header, payload, sig
        encodes encoding_alg (from header) alg(header + "." + payload)
        then compares it to sig. If its correct, and exp is valid, it returns the decoded payload. 
        If not, it throws and error corrsponding to the reason of invalidity
    Returns address 
    """
    print(jwt_token)
    try:
        payload = jwt.decode(jwt_token, ACCESS_SECRET, algorithms=["HS256"])
        address = payload["sub"]
        
    except jwt.InvalidSignatureError:
        return build_response(401, {"error_code": "InvalidSignatureError"})
    except jwt.ExpiredSignatureError:
        return build_response(401, {"error_code": "ExpiredSignatureError"})
    except Exception:
        return build_response(401, {"error_code": "jwt token invalid."})
    
    return {"address" : address}